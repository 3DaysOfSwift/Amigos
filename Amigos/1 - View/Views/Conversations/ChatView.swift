import SwiftUI

struct ChatView: View {
    @Environment(ThemeManager.self) private var themeManager
    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    let context: ChatContext
    @State private var viewModel = ChatViewModel()
    @FocusState private var isComposerFocused: Bool
    @Namespace private var admissionCoinAnimation
    @State private var scrollPosition = ScrollPosition(edge: .bottom)

    private var palette: AppPalette { themeManager.currentTheme.palette }

    var body: some View {
        let conversation = viewModel.conversation(for: context)

        ScrollViewReader { proxy in
            ScrollView {
                LazyVStack(alignment: .leading, spacing: 20) {
                    ChatIntroduction(context: context)

                    Text("Messages are generated by AI. Some may be inaccurate or inappropriate.")
                        .font(.footnote)
                        .foregroundStyle(palette.mutedText)
                        .multilineTextAlignment(.center)
                        .frame(maxWidth: .infinity)
                        .padding(16)
                        .background(palette.surface, in: RoundedRectangle(cornerRadius: 18))

                    if conversation.messages.isEmpty && !context.startsWithGreeting {
                        VStack(alignment: .leading, spacing: 10) {
                            Label(context.scenario?.title ?? "Say hello", systemImage: context.scenario?.symbol ?? "bubble.left.fill")
                                .font(.headline)
                            Text(context.scenario?.objective ?? "Start naturally in Spanish. Your friend will keep the conversation moving.")
                                .foregroundStyle(palette.mutedText)
                            if let scenario = context.scenario {
                                Text("You are the \(scenario.learnerRole). Your partner is the \(scenario.aiRole).")
                                    .font(.subheadline)
                                    .foregroundStyle(palette.mutedText)
                            }
                        }
                        .padding(20)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(palette.surface, in: RoundedRectangle(cornerRadius: 22))

                        if context.scenario == nil {
                            Label("Earn a doubloon after 10 exchanges today, then another for every 40 more.", systemImage: "sparkles")
                                .font(.footnote)
                                .foregroundStyle(palette.mutedText)
                        }
                    }

                    ForEach(conversation.messages) { message in
                        if message.startsNewConversation == true {
                            Divider()
                                .padding(.vertical, 8)
                                .accessibilityLabel("New conversation")
                        }
                        ChatBubble(message: message, translation: viewModel.translationDisplay(for: message), onTap: {
                            viewModel.toggleTranslation(for: message)
                        }, onTranslationAppear: {
                            withAnimation(reduceMotion ? nil : .easeInOut(duration: 0.2)) {
                                proxy.scrollTo("translation-\(message.id)")
                            }
                        })
                        .id(message.id)
                    }
                    if let pending = viewModel.pendingMessage {
                        ChatBubble(message: pending, translation: .hidden, onTap: nil).opacity(0.7)
                            .id(pending.id)
                    }
                    if viewModel.offersNotificationPermission(in: context) {
                        VStack(alignment: .leading, spacing: 12) {
                            Button("Enable notifications") {
                                Task { await viewModel.answerNotificationInvitation(enable: true) }
                            }
                            .buttonStyle(.borderedProminent)
                            Button("Not now") {
                                Task { await viewModel.answerNotificationInvitation(enable: false) }
                            }
                            .buttonStyle(.bordered)
                        }
                        .disabled(viewModel.isAnsweringNotificationInvitation || viewModel.isSending)
                    }
                    if viewModel.isResponding() {
                        HStack {
                            HStack(spacing: 5) {
                                ForEach(0..<3) { index in
                                    if reduceMotion {
                                        Circle().frame(width: 6, height: 6)
                                    } else {
                                        Circle()
                                            .frame(width: 6, height: 6)
                                            .keyframeAnimator(initialValue: 0.0, repeating: true) { dot, lift in
                                                dot.offset(y: -lift)
                                            } keyframes: { _ in
                                                LinearKeyframe(0.0, duration: 0.05 + Double(index) * 0.12)
                                                CubicKeyframe(5.0, duration: 0.15)
                                                CubicKeyframe(0.0, duration: 0.15)
                                                LinearKeyframe(0.0, duration: 0.65 - Double(index) * 0.12)
                                            }
                                    }
                                }
                            }
                                .frame(height: 24)
                                .foregroundStyle(palette.accent)
                                .padding(.horizontal, 22)
                                .padding(.vertical, 12)
                                .background(palette.friendBubble, in: RoundedRectangle(cornerRadius: 22))
                            Spacer()
                        }
                        .accessibilityElement(children: .ignore)
                        .accessibilityLabel("\(context.title) is replying")
                    }
                    if conversation.finished {
                        VStack(alignment: .leading, spacing: 14) {
                            Label("Role Play complete", systemImage: "checkmark.seal.fill")
                                .font(.headline)
                                .foregroundStyle(palette.accent)
                            Button("Practise again") { Task { await viewModel.practiseAgain(context) } }
                                .buttonStyle(.borderedProminent)
                        }
                        .padding(20)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(palette.surface, in: RoundedRectangle(cornerRadius: 22))
                    }
                    if let error = viewModel.error {
                        Text(error).font(.footnote).foregroundStyle(.red)
                        if viewModel.greetingFailed {
                            Button("Retry greeting") {
                                Task { await viewModel.startSuggestedChat(context) }
                            }
                        }
                    }
                    if let notice = viewModel.profileNotice {
                        Text(notice)
                            .font(.footnote)
                            .foregroundStyle(palette.mutedText)
                    }
                }
                .padding(18)
            }
            .defaultScrollAnchor(.bottom, for: .sizeChanges)
            .defaultScrollAnchor(.bottom, for: .initialOffset)
            .scrollPosition($scrollPosition)
            .onAppear {
                if !conversation.messages.isEmpty {
                    scrollPosition.scrollTo(edge: .bottom)
                }
            }
            .onChange(of: conversation.messages.last?.id) { _, messageID in
                if messageID != nil {
                    withAnimation(reduceMotion ? nil : .easeOut(duration: 0.2)) {
                        scrollPosition.scrollTo(edge: .bottom)
                    }
                }
            }
            .onChange(of: viewModel.pendingMessage?.id) { _, pendingID in
                if pendingID != nil || !conversation.messages.isEmpty {
                    withAnimation(reduceMotion ? nil : .easeOut(duration: 0.2)) {
                        scrollPosition.scrollTo(edge: .bottom)
                    }
                }
            }
        }
        .task(id: context) {
            if context.startsWithGreeting { await viewModel.startSuggestedChat(context) }
        }
        .safeAreaInset(edge: .bottom, spacing: 0) {
            if !conversation.finished && !viewModel.showsRolePlayAdmission(context) {
                composer
                    .transition(.opacity)
            }
        }
        .overlay(alignment: .bottom) {
            if !conversation.finished && viewModel.showsRolePlayAdmission(context) {
                admissionBar
                    .transition(reduceMotion ? .opacity : .move(edge: .bottom))
            }
        }
        .animation(reduceMotion ? .easeOut(duration: 0.12) : .spring(response: 0.45, dampingFraction: 0.84),
                   value: viewModel.admissionPhase)
        .overlay {
            if viewModel.isCelebratingAdmission {
                Color.black.opacity(reduceMotion ? 0.15 : 0.38)
                    .ignoresSafeArea()
                    .transition(.opacity)
                    .allowsHitTesting(true)
                VStack(spacing: 14) {
                    ZStack {
                        Circle().fill(Color.green.opacity(0.20))
                        if viewModel.admissionPhase == .centering {
                            DoubloonIcon(size: 84)
                        } else {
                            Image(systemName: "checkmark")
                                .font(.system(size: 38, weight: .bold))
                                .foregroundStyle(Color.green)
                                .symbolEffect(.bounce, options: .nonRepeating, isActive: !reduceMotion)
                        }
                    }
                    .frame(width: 96, height: 96)
                    .matchedGeometryEffect(id: "admission-coin", in: admissionCoinAnimation,
                                           properties: reduceMotion ? [] : .frame)
                    Text("Ready to role-play")
                        .font(.title3.weight(.bold))
                    Text("\(context.cost) doubloons will be charged after your first reply.")
                        .font(.subheadline)
                        .foregroundStyle(palette.mutedText)
                        .multilineTextAlignment(.center)
                }
                .padding(26)
                .background(palette.surface, in: RoundedRectangle(cornerRadius: 28))
                .padding(28)
                .transition(.scale(scale: 0.85).combined(with: .opacity))
                .accessibilityElement(children: .combine)
            }
        }
        .sensoryFeedback(.success, trigger: viewModel.admissionSuccess)
        .onDisappear { viewModel.cancelAdmissionAnimation() }
        .background {
            ChatWallpaperView(wallpaper: themeManager.currentWallpaper, palette: palette)
                .ignoresSafeArea()
        }
        .navigationBarTitleDisplayMode(.inline)
        .hidesAppTabBar()
        .toolbar {
            ToolbarItem(placement: .principal) {
                NavigationLink {
                    AmigoBioView(amigo: context.amigo)
                } label: {
                    HStack(spacing: 9) {
                        AmigoPortrait(amigo: context.amigo, size: 34)
                        VStack(alignment: .leading, spacing: 1) {
                            Text(context.amigo.name).font(.headline)
                            Text(context.scenario?.title ?? "Your amigo")
                                .font(.caption)
                                .foregroundStyle(palette.mutedText)
                        }
                    }
                }
                .buttonStyle(.plain)
                .accessibilityLabel("About \(context.amigo.name)")
            }
            ToolbarItem(placement: .topBarTrailing) {
                HStack(spacing: 5) {
                    DoubloonIcon(size: 27)
                    Text("\(viewModel.doubloons)")
                        .font(.subheadline.weight(.semibold))
                        .monospacedDigit()
                }
                .padding(.horizontal, 8)
                .accessibilityElement(children: .combine)
                .accessibilityLabel("\(viewModel.doubloons) doubloons")
            }
        }
    }

    private var composer: some View {
        VStack(spacing: 10) {
            if viewModel.canFinishRolePlay(in: context) {
                Button("Complete Role Play") { Task { await viewModel.finishRolePlay(in: context) } }
                    .buttonStyle(.borderedProminent)
                    .disabled(viewModel.isResponding())
            }
            HStack(alignment: .bottom, spacing: 12) {
                LearnerPortrait(size: 32)
                    .padding(.bottom, 5)

                TextField("Message in Spanish", text: $viewModel.draft, axis: .vertical)
                    .focused($isComposerFocused)
                    .onAppear { isComposerFocused = true }
                    .onDisappear { isComposerFocused = false }
                    .lineLimit(1...4)
                    .onSubmit { Task { await viewModel.send(in: context) } }
                    .padding(.vertical, 10)
                    .accessibilityLabel("Message in Spanish")

                Button { Task { await viewModel.send(in: context) } } label: {
                    Image(systemName: "arrow.up")
                        .font(.headline.weight(.bold))
                        .frame(width: 42, height: 42)
                }
                .buttonStyle(.plain)
                .background(palette.accent, in: Circle())
                .foregroundStyle(themeManager.currentTheme.colourScheme == .dark ? Color.black : Color.white)
                .disabled(!viewModel.canSend(in: context))
                .accessibilityLabel("Send message")
            }
            .padding(.horizontal, 16)
            .padding(.vertical, 7)
            .background(palette.surface, in: RoundedRectangle(cornerRadius: 24))
        }
        .padding(.horizontal, 16)
        .padding(.top, 12)
        .padding(.bottom, 8)
        .background(palette.background)
    }

    private var admissionBar: some View {
        VStack(spacing: 10) {
            if viewModel.doubloons < context.cost {
                Text("You need \(context.cost) doubloons to continue.")
                    .font(.footnote)
                    .foregroundStyle(.yellow)
            }
            RolePlayAdmissionView(
                cost: context.cost,
                canConfirm: viewModel.canAuthorizeRolePlay(context),
                phase: viewModel.admissionPhase,
                coinAnimation: admissionCoinAnimation
            ) {
                viewModel.authorizeRolePlay(context)
            }
        }
        .padding(.horizontal, 16)
        .padding(.top, 16)
        .padding(.bottom, 150)
        .frame(maxWidth: .infinity)
        .background {
            UnevenRoundedRectangle(topLeadingRadius: 24, topTrailingRadius: 24)
                .fill(palette.background)
                .ignoresSafeArea(edges: .bottom)
        }
    }
}

private struct ChatIntroduction: View {
    @Environment(ThemeManager.self) private var themeManager
    let context: ChatContext

    var body: some View {
        VStack(spacing: 12) {
            NavigationLink {
                AmigoBioView(amigo: context.amigo)
            } label: {
                VStack(spacing: 12) {
                    AmigoPortrait(amigo: context.amigo, size: 76)
                    Text(context.amigo.name)
                        .font(.system(.title2, design: .rounded, weight: .bold))
                }
            }
            .buttonStyle(.plain)
            .accessibilityLabel("About \(context.amigo.name)")
            Text(context.scenario?.context.capitalized ?? context.amigo.identity)
                .font(.subheadline)
                .foregroundStyle(themeManager.currentTheme.palette.mutedText)
                .multilineTextAlignment(.center)
        }
        .frame(maxWidth: .infinity)
        .padding(.bottom, 6)
    }
}

private struct ChatBubble: View {
    @Environment(ThemeManager.self) private var themeManager
    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    let message: ChatMessage
    let translation: ChatViewModel.TranslationDisplay
    let onTap: (() -> Void)?
    var onTranslationAppear: (() -> Void)? = nil

    var body: some View {
        let isLearner = message.role == .learner
        let palette = themeManager.currentTheme.palette

        VStack(alignment: isLearner ? .trailing : .leading, spacing: 7) {
                Button { onTap?() } label: {
                    Text(message.text)
                        .font(.body)
                        .multilineTextAlignment(.leading)
                        .padding(.leading, isLearner ? 17 : 27)
                        .padding(.trailing, isLearner ? 27 : 17)
                        .padding(.vertical, 13)
                        .background(isLearner ? palette.learnerBubble : palette.friendBubble,
                                    in: ChatBubbleShape(tailOnRight: isLearner))
                }
                .buttonStyle(.plain)
                .disabled(onTap == nil)
                .accessibilityHint("Show or hide the English translation")

                switch translation {
                case .hidden:
                    EmptyView()
                case .translated(let english):
                    Button { onTap?() } label: {
                        VStack(alignment: .leading, spacing: 3) {
                            Text("ENGLISH")
                                .font(.caption2.weight(.bold))
                                .tracking(1)
                                .foregroundStyle(palette.accent)
                            Text(english)
                                .font(.subheadline)
                                .multilineTextAlignment(.leading)
                                .fixedSize(horizontal: false, vertical: true)
                        }
                        .padding(13)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(palette.accent.opacity(0.18), in: RoundedRectangle(cornerRadius: 15))
                    }
                    .buttonStyle(.plain)
                    .accessibilityHint("Hide the English translation")
                    .id("translation-\(message.id)")
                    .onAppear { onTranslationAppear?() }
                }
        }
        .frame(maxWidth: .infinity, alignment: isLearner ? .trailing : .leading)
        .padding(isLearner ? .leading : .trailing, 56)
        .animation(reduceMotion ? nil : .easeInOut(duration: 0.2), value: translation)
    }
}

private struct ChatBubbleShape: Shape {
    let tailOnRight: Bool

    func path(in rect: CGRect) -> Path {
        let tailWidth: CGFloat = 4
        let bubble = CGRect(x: tailOnRight ? 0 : tailWidth,
                            y: 0, width: rect.width - tailWidth, height: rect.height)
        var path = Path(roundedRect: bubble, cornerRadius: 22)

        if tailOnRight {
            path.move(to: CGPoint(x: bubble.maxX - 10, y: bubble.maxY - 15))
            path.addQuadCurve(to: CGPoint(x: rect.maxX, y: rect.maxY - 2),
                              control: CGPoint(x: bubble.maxX, y: bubble.maxY - 8))
            path.addQuadCurve(to: CGPoint(x: bubble.maxX - 13, y: bubble.maxY - 3),
                              control: CGPoint(x: bubble.maxX - 2, y: bubble.maxY))
        } else {
            path.move(to: CGPoint(x: bubble.minX + 13, y: bubble.maxY - 3))
            path.addQuadCurve(to: CGPoint(x: rect.minX, y: rect.maxY - 2),
                              control: CGPoint(x: bubble.minX + 2, y: bubble.maxY))
            path.addQuadCurve(to: CGPoint(x: bubble.minX + 10, y: bubble.maxY - 15),
                              control: CGPoint(x: bubble.minX, y: bubble.maxY - 8))
        }
        path.closeSubpath()
        return path
    }
}
