import SwiftUI

struct ChatView: View {
    @Environment(ThemeManager.self) private var themeManager
    let context: ChatContext
    @State private var viewModel = ChatViewModel()

    private var palette: AppPalette { themeManager.currentTheme.palette }

    var body: some View {
        let conversation = viewModel.conversation(for: context)

        ScrollViewReader { proxy in
            ScrollView {
                LazyVStack(alignment: .leading, spacing: 20) {
                    ChatIntroduction(context: context)

                    Text("Messages are generated by AI. Some may be inaccurate or inappropriate.")
                        .font(.footnote)
                        .foregroundStyle(palette.mutedText)
                        .multilineTextAlignment(.center)
                        .frame(maxWidth: .infinity)
                        .padding(16)
                        .background(palette.surface, in: RoundedRectangle(cornerRadius: 18))

                    if conversation.messages.isEmpty {
                        VStack(alignment: .leading, spacing: 10) {
                            Label(context.scenario?.title ?? "Say hello", systemImage: context.scenario?.symbol ?? "bubble.left.fill")
                                .font(.headline)
                            Text(context.scenario?.objective ?? "Start naturally in Spanish. Your friend will keep the conversation moving.")
                                .foregroundStyle(palette.mutedText)
                            if let scenario = context.scenario {
                                Text("You are the \(scenario.learnerRole). Your partner is the \(scenario.aiRole).")
                                    .font(.subheadline)
                                    .foregroundStyle(palette.mutedText)
                            }
                        }
                        .padding(20)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(palette.surface, in: RoundedRectangle(cornerRadius: 22))

                        HStack(alignment: .top, spacing: 12) {
                            DoubloonIcon(size: 24)
                            VStack(alignment: .leading, spacing: 4) {
                                Text("\(context.cost) \(context.cost == 1 ? "doubloon" : "doubloons") · one conversation")
                                    .font(.subheadline.weight(.semibold))
                                Text("Charged only after your first successful reply. Return within ten minutes to continue.")
                                    .font(.footnote)
                                    .foregroundStyle(palette.mutedText)
                            }
                        }
                        .padding(18)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(palette.surface, in: RoundedRectangle(cornerRadius: 20))
                    }

                    ForEach(conversation.messages) { message in
                        ChatBubble(message: message).id(message.id)
                    }
                    if let pending = viewModel.pendingMessage {
                        ChatBubble(message: pending).opacity(0.7)
                    }
                    if viewModel.isResponding() {
                        HStack {
                            Text("•••")
                                .font(.title2.bold())
                                .foregroundStyle(palette.accent)
                                .padding(.horizontal, 22)
                                .padding(.vertical, 12)
                                .background(palette.friendBubble, in: RoundedRectangle(cornerRadius: 22))
                            Spacer()
                        }
                        .accessibilityLabel("\(context.title) is replying")
                    }
                    if conversation.finished {
                        VStack(alignment: .leading, spacing: 14) {
                            Label("Role Play complete", systemImage: "checkmark.seal.fill")
                                .font(.headline)
                                .foregroundStyle(palette.accent)
                            Button("Practise again") { Task { await viewModel.practiseAgain(context) } }
                                .buttonStyle(.borderedProminent)
                        }
                        .padding(20)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(palette.surface, in: RoundedRectangle(cornerRadius: 22))
                    }
                    if let error = viewModel.error {
                        Text(error).font(.footnote).foregroundStyle(.red)
                    }
                }
                .padding(18)
            }
            .defaultScrollAnchor(.bottom, for: .sizeChanges)
            .onChange(of: conversation.messages.count) { _, _ in
                if let last = conversation.messages.last {
                    withAnimation { proxy.scrollTo(last.id, anchor: .bottom) }
                }
            }
        }
        .safeAreaInset(edge: .bottom, spacing: 0) {
            if !conversation.finished { composer }
        }
        .background {
            ChatWallpaperView(wallpaper: themeManager.currentWallpaper, palette: palette)
                .ignoresSafeArea()
        }
        .navigationBarTitleDisplayMode(.inline)
        .toolbar(.hidden, for: .tabBar)
        .toolbarBackground(palette.surface, for: .navigationBar)
        .toolbarBackground(.visible, for: .navigationBar)
        .toolbar {
            ToolbarItem(placement: .principal) {
                NavigationLink {
                    AmigoBioView(amigo: context.amigo)
                } label: {
                    HStack(spacing: 9) {
                        AmigoPortrait(amigo: context.amigo, size: 34)
                        VStack(alignment: .leading, spacing: 1) {
                            Text(context.amigo.name).font(.headline)
                            Text(context.scenario?.title ?? "Your amigo")
                                .font(.caption)
                                .foregroundStyle(palette.mutedText)
                        }
                    }
                }
                .buttonStyle(.plain)
                .accessibilityLabel("About \(context.amigo.name)")
            }
            ToolbarItem(placement: .topBarTrailing) {
                NavigationLink {
                    WalletView()
                } label: {
                    DoubloonIcon(size: 27)
                        .frame(width: 44, height: 44)
                        .accessibilityLabel("Show doubloons")
                }
            }
        }
    }

    private var composer: some View {
        VStack(spacing: 10) {
            if viewModel.canClaimReward(in: context) {
                Button("Claim today’s chat doubloon") { Task { await viewModel.claimReward(in: context) } }
                    .buttonStyle(.borderedProminent)
                    .disabled(viewModel.isResponding())
            }
            if viewModel.canFinishRolePlay(in: context) {
                Button("Complete Role Play") { Task { await viewModel.finishRolePlay(in: context) } }
                    .buttonStyle(.borderedProminent)
                    .disabled(viewModel.isResponding())
            }
            if !viewModel.hasEnoughDoubloons(for: context) {
                Text("You need \(context.cost) doubloons to continue.")
                    .font(.footnote)
                    .foregroundStyle(.yellow)
            }
            HStack(alignment: .bottom, spacing: 12) {
                LearnerPortrait(size: 32)
                    .padding(.bottom, 5)

                TextField("Message in Spanish", text: $viewModel.draft, axis: .vertical)
                    .lineLimit(1...4)
                    .onSubmit { Task { await viewModel.send(in: context) } }
                    .padding(.vertical, 10)
                    .accessibilityLabel("Message in Spanish")

                Button { Task { await viewModel.send(in: context) } } label: {
                    Image(systemName: "arrow.up")
                        .font(.headline.weight(.bold))
                        .frame(width: 42, height: 42)
                }
                .buttonStyle(.plain)
                .background(palette.accent, in: Circle())
                .foregroundStyle(themeManager.currentTheme.colourScheme == .dark ? Color.black : Color.white)
                .disabled(!viewModel.canSend(in: context))
                .accessibilityLabel("Send message")
            }
            .padding(.horizontal, 16)
            .padding(.vertical, 7)
            .background(palette.surface, in: RoundedRectangle(cornerRadius: 24))
        }
        .padding(.horizontal, 16)
        .padding(.top, 12)
        .padding(.bottom, 8)
        .background(palette.background)
    }
}

private struct ChatIntroduction: View {
    @Environment(ThemeManager.self) private var themeManager
    let context: ChatContext

    var body: some View {
        VStack(spacing: 12) {
            NavigationLink {
                AmigoBioView(amigo: context.amigo)
            } label: {
                VStack(spacing: 12) {
                    AmigoPortrait(amigo: context.amigo, size: 76)
                    Text(context.amigo.name)
                        .font(.system(.title2, design: .rounded, weight: .bold))
                }
            }
            .buttonStyle(.plain)
            .accessibilityLabel("About \(context.amigo.name)")
            Text(context.scenario?.context.capitalized ?? context.amigo.identity)
                .font(.subheadline)
                .foregroundStyle(themeManager.currentTheme.palette.mutedText)
                .multilineTextAlignment(.center)
        }
        .frame(maxWidth: .infinity)
        .padding(.bottom, 6)
    }
}

private struct ChatBubble: View {
    @Environment(ThemeManager.self) private var themeManager
    let message: ChatMessage

    var body: some View {
        let isLearner = message.role == .learner

        HStack {
            if isLearner { Spacer(minLength: 56) }
            Text(message.text)
                .font(.body)
                .padding(.leading, isLearner ? 17 : 27)
                .padding(.trailing, isLearner ? 27 : 17)
                .padding(.vertical, 13)
                .background(isLearner
                            ? themeManager.currentTheme.palette.learnerBubble
                            : themeManager.currentTheme.palette.friendBubble,
                            in: ChatBubbleShape(tailOnRight: isLearner))
            if !isLearner { Spacer(minLength: 56) }
        }
    }
}

private struct ChatBubbleShape: Shape {
    let tailOnRight: Bool

    func path(in rect: CGRect) -> Path {
        let tailWidth: CGFloat = 10
        let bubble = CGRect(x: tailOnRight ? 0 : tailWidth,
                            y: 0, width: rect.width - tailWidth, height: rect.height)
        var path = Path(roundedRect: bubble, cornerRadius: 22)

        if tailOnRight {
            path.move(to: CGPoint(x: bubble.maxX - 13, y: bubble.maxY - 12))
            path.addQuadCurve(to: CGPoint(x: rect.maxX, y: rect.maxY),
                              control: CGPoint(x: bubble.maxX, y: bubble.maxY - 2))
            path.addQuadCurve(to: CGPoint(x: bubble.maxX - 19, y: bubble.maxY - 5),
                              control: CGPoint(x: bubble.maxX - 3, y: bubble.maxY))
        } else {
            path.move(to: CGPoint(x: bubble.minX + 19, y: bubble.maxY - 5))
            path.addQuadCurve(to: CGPoint(x: rect.minX, y: rect.maxY),
                              control: CGPoint(x: bubble.minX + 3, y: bubble.maxY))
            path.addQuadCurve(to: CGPoint(x: bubble.minX + 13, y: bubble.maxY - 12),
                              control: CGPoint(x: bubble.minX, y: bubble.maxY - 2))
        }
        path.closeSubpath()
        return path
    }
}
